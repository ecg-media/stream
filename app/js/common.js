/** Returns an inline SVG element for the named Material icon. */
function icon(name) {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', 'icon');
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  path.setAttribute('d', ICONS[name] || '');
  svg.append(path);
  return svg;
}

/** Replaces every element with a data-icon attribute below root by its icon. */
function renderIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => el.replaceWith(icon(el.dataset.icon)));
}

function storageGet(key) {
  try { return localStorage.getItem(key); } catch { return null; }
}

function storageSet(key, value) {
  try {
    if (value == null) localStorage.removeItem(key);
    else localStorage.setItem(key, value);
  } catch { /* storage unavailable */ }
}

/** Returns the active color theme ("light" or "dark"). */
function currentTheme() {
  return document.documentElement.dataset.theme;
}

/** Applies a color theme; the choice is remembered for the next visit. */
function setTheme(theme, remember = true) {
  document.documentElement.dataset.theme = theme;
  document.querySelector('meta[name="theme-color"]')?.setAttribute('content', theme === 'dark' ? '#1f2124' : '#f6f4ef');
  if (remember) storageSet('theme', theme);
  document.querySelectorAll('[data-theme-toggle]').forEach((btn) => btn.replaceChildren(icon(theme === 'dark' ? 'light_mode' : 'dark_mode')));
}

/** Connects to the server and returns { socket, request(event, data) }. */
function connect(auth) {
  const socket = io({ auth });
  const request = (event, data = {}) => new Promise((resolve, reject) => {
    socket.timeout(15000).emit(event, data, (timeoutErr, err, result) => {
      if (timeoutErr) reject(new Error('timeout'));
      else if (err) reject(new Error(err));
      else resolve(result);
    });
  });
  return { socket, request };
}

